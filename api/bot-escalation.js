// Bot Escalation API - Handle CruiseHelperBot escalations
// Sends escalated questions to admin@interlineasia.com

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    res.setHeader('Allow', ['POST']);
    return res.status(405).json({ error: 'Method not allowed' });
  }

  try {
    const { name, email, question, timestamp, page } = req.body;
    
    // Basic validation
    if (!name || !email || !question) {
      return res.status(400).json({ 
        error: 'Missing required fields: name, email, and question are required' 
      });
    }
    
    // Email validation
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return res.status(400).json({ 
        error: 'Invalid email format' 
      });
    }
    
    // Log escalation (for internal tracking)
    console.log('Bot Escalation Received:', {
      name: name.substring(0, 20),
      email: email.substring(0, 30),
      question: question.substring(0, 100),
      timestamp,
      page
    });
    
    // Prepare escalation email
    const escalationData = {
      to: 'admin@interlineasia.com',
      subject: `Cruise Bot Escalation - ${name}`,
      html: `
        <h2>🤖 CruiseHelper Bot Escalation</h2>
        
        <div style="background: #f8fafc; padding: 20px; border-radius: 8px; margin: 20px 0;">
          <h3>Customer Information</h3>
          <p><strong>Name:</strong> ${name}</p>
          <p><strong>Email:</strong> ${email}</p>
          <p><strong>Page:</strong> ${page || 'Unknown'}</p>
          <p><strong>Timestamp:</strong> ${timestamp}</p>
        </div>
        
        <div style="background: #fff7ed; padding: 20px; border-radius: 8px; margin: 20px 0;">
          <h3>Customer Question</h3>
          <p style="font-style: italic; line-height: 1.6;">"${question}"</p>
        </div>
        
        <div style="background: #ecfdf5; padding: 20px; border-radius: 8px; margin: 20px 0;">
          <h3>⚠️ Important Notes</h3>
          <ul>
            <li>This customer question could not be answered by our CruiseHelper bot</li>
            <li>Please respond directly to the customer at: <strong>${email}</strong></li>
            <li>Do NOT reply to this escalation email</li>
            <li>Customer data is private - do not share with third parties</li>
          </ul>
        </div>
        
        <hr style="margin: 30px 0;">
        <p style="color: #6b7280; font-size: 14px;">
          This escalation was automatically generated by the CruiseHelper bot system.<br>
          Interline Asia - Exclusive Cruise Deals for Travel Industry Professionals
        </p>
      `
    };
    
    // Here you would integrate with your email service (Brevo, etc.)
    // For now, we'll simulate the email sending
    
    try {
      // Simulate email sending (replace with actual email service)
      console.log('Escalation email would be sent:', escalationData);
      
      // Optional: Log to secure file for internal tracking
      const logEntry = {
        timestamp: new Date().toISOString(),
        name: name.substring(0, 50), // Truncate for privacy
        email: email.substring(0, 100),
        question: question.substring(0, 500),
        page: page || 'unknown',
        status: 'escalated'
      };
      
      // You could append to a secure log file here
      // await appendToSecureLog('bot-escalations.json', logEntry);
      
      return res.status(200).json({
        success: true,
        message: 'Escalation sent successfully. Our team will contact you within 24 hours.',
        reference: `ESC-${Date.now()}`
      });
      
    } catch (emailError) {
      console.error('Email sending failed:', emailError);
      
      // Still return success to user, but log the error
      return res.status(200).json({
        success: true,
        message: 'Your message has been received. Our team will contact you within 24 hours.',
        reference: `ESC-${Date.now()}`,
        note: 'Email delivery pending'
      });
    }
    
  } catch (error) {
    console.error('Bot escalation error:', error);
    return res.status(500).json({ 
      error: 'Internal server error during escalation processing' 
    });
  }
}

